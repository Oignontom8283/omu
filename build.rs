//! Generates `branding.rs` (constants) from the workspace's `branding.toml`.

use std::{env, fs, path::PathBuf};

const STRINGS: &[&str] = &[
    "display_name",
    "slug",
    "cli_executable",
    "daemon_executable",
    "gui_executable",
    "app_id",
    "data_dir_name",
    "env_prefix",
    "single_instance_name",
    "virtual_manufacturer",
];
const INTEGERS: &[&str] = &[
    "virtual_vendor_id",
    "virtual_product_id",
    "virtual_server_port",
    "sound_cache_mb",
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let path = manifest.join("branding.toml");
    println!("cargo:rerun-if-changed={}", path.display());
    let text =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let table: toml::Table = text
        .parse()
        .unwrap_or_else(|e| panic!("invalid branding.toml: {e}"));

    let mut out = String::from("// @generated by build.rs from branding.toml: do not edit.\n");
    for key in STRINGS {
        let value = table
            .get(*key)
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("branding.toml: `{key}` must be a string"));
        out.push_str(&format!(
            "pub const {}: &str = {:?};\n",
            key.to_uppercase(),
            value
        ));
    }
    for key in INTEGERS {
        let value = table
            .get(*key)
            .and_then(|v| v.as_integer())
            .unwrap_or_else(|| panic!("branding.toml: `{key}` must be an integer"));
        assert!(
            (0..=0xffff).contains(&value),
            "branding.toml: `{key}` must fit in 16 bits"
        );
        out.push_str(&format!(
            "pub const {}: u16 = {};\n",
            key.to_uppercase(),
            value
        ));
    }
    fs::write(
        PathBuf::from(env::var("OUT_DIR").unwrap()).join("branding.rs"),
        out,
    )
    .unwrap();

    // The window embeds the panel too, and takes its name from the branding.
    #[cfg(feature = "gui")]
    gui::prepare(&path);

    // The daemon embeds the web panel built into ui/dist: build it (with npm) whenever the daemon is built. The
    // folder must exist for the embedding even when `OMU_SKIP_UI` skips the build.
    if env::var_os("CARGO_FEATURE_WEB_PANEL").is_some()
        || env::var_os("CARGO_FEATURE_GUI").is_some()
    {
        panel::ensure_panel(&manifest.join("ui"), &path);
    } else {
        let _ = fs::create_dir_all(manifest.join("ui").join("dist"));
    }
}

/// Builds the web panel (`ui/`) with npm, so that building the daemon or the desktop window always embeds an
/// up-to-date panel.
///
/// * works on Windows (`npm.cmd`) and elsewhere (`npm`);
/// * skips the work when `ui/dist` is newer than every input (so a normal `cargo build` costs one directory scan);
/// * a lock file keeps two builds that run at the same time (debug and release, an editor's check) from running npm
///   together;
/// * `OMU_SKIP_UI=1` builds without the panel (CI without Node.js): the daemon then serves a page saying so.
mod panel {
    use std::path::{Path, PathBuf};
    use std::process::Command;
    use std::time::{Duration, SystemTime};

    /// Name of the npm executable: on Windows it is a `.cmd` file, which `Command` only finds when named in full.
    fn npm() -> &'static str {
        if cfg!(windows) {
            "npm.cmd"
        } else {
            "npm"
        }
    }

    fn newest(path: &Path, newest_seen: &mut SystemTime) {
        let Ok(meta) = std::fs::metadata(path) else {
            return;
        };
        if meta.is_dir() {
            let Ok(entries) = std::fs::read_dir(path) else {
                return;
            };
            for entry in entries.flatten() {
                let name = entry.file_name();
                if name == "node_modules" || name == "dist" {
                    continue;
                }
                newest(&entry.path(), newest_seen);
            }
        } else if let Ok(modified) = meta.modified() {
            if modified > *newest_seen {
                *newest_seen = modified;
            }
        }
    }

    /// Whether `ui/dist` is missing or older than the panel's sources (or the branding it reads).
    fn panel_is_stale(ui: &Path, branding: &Path) -> bool {
        let Ok(built) =
            std::fs::metadata(ui.join("dist").join("index.html")).and_then(|m| m.modified())
        else {
            return true;
        };
        let mut latest = SystemTime::UNIX_EPOCH;
        newest(ui, &mut latest);
        newest(branding, &mut latest);
        latest > built
    }

    fn run_npm(ui: &Path, args: &[&str]) -> Result<(), String> {
        let status = Command::new(npm())
            .args(args)
            .current_dir(ui)
            .status()
            .map_err(|e| {
                format!(
                    "cannot run `{} {}`: {e}. Node.js (with npm) is needed to build the web panel: install it from \
                     https://nodejs.org, or set OMU_SKIP_UI=1 to build without the panel",
                    npm(),
                    args.join(" ")
                )
            })?;
        status
            .success()
            .then_some(())
            .ok_or_else(|| format!("`{} {}` failed ({status})", npm(), args.join(" ")))
    }

    struct Lock(PathBuf);

    impl Lock {
        /// Waits (up to two minutes) for the other build script, then takes the lock.
        fn take(path: PathBuf) -> Lock {
            for _ in 0..1200 {
                if std::fs::OpenOptions::new()
                    .write(true)
                    .create_new(true)
                    .open(&path)
                    .is_ok()
                {
                    return Lock(path);
                }
                // a lock older than ten minutes belongs to a build that died
                if std::fs::metadata(&path)
                    .and_then(|m| m.modified())
                    .is_ok_and(|t| t.elapsed().unwrap_or_default() > Duration::from_secs(600))
                {
                    let _ = std::fs::remove_file(&path);
                }
                std::thread::sleep(Duration::from_millis(100));
            }
            Lock(path)
        }
    }

    impl Drop for Lock {
        fn drop(&mut self) {
            let _ = std::fs::remove_file(&self.0);
        }
    }

    /// Makes sure `<ui>/dist` holds the built panel. Panics (failing the build) with an explanation when npm is missing
    /// or fails, unless `OMU_SKIP_UI` is set.
    pub fn ensure_panel(ui: &Path, branding: &Path) {
        println!("cargo:rerun-if-env-changed=OMU_SKIP_UI");
        for input in [
            "src",
            "index.html",
            "package.json",
            "package-lock.json",
            "tsconfig.json",
            "vite.config.ts",
        ] {
            println!("cargo:rerun-if-changed={}", ui.join(input).display());
        }
        let _ = std::fs::create_dir_all(ui.join("dist"));
        if std::env::var_os("OMU_SKIP_UI").is_some() {
            println!("cargo:warning=OMU_SKIP_UI is set: building without the web panel");
            return;
        }
        if !ui.join("package.json").exists() {
            return;
        }
        let _lock = Lock::take(ui.join(".panel-build.lock"));
        // another build script may have finished the work while this one waited
        if !panel_is_stale(ui, branding) {
            return;
        }
        let installed = ui.join("node_modules").join(".package-lock.json");
        let lock = ui.join("package-lock.json");
        let deps_stale = match (
            std::fs::metadata(&installed).and_then(|m| m.modified()),
            std::fs::metadata(&lock).and_then(|m| m.modified()),
        ) {
            (Ok(i), Ok(l)) => l > i,
            (Err(_), _) => true,
            _ => false,
        };
        let result = (|| {
            if deps_stale {
                let install: &[&str] = if lock.exists() {
                    &["ci", "--no-audit", "--no-fund", "--loglevel=error"]
                } else {
                    &["install", "--no-audit", "--no-fund", "--loglevel=error"]
                };
                run_npm(ui, install)?;
            }
            run_npm(ui, &["run", "build"])
        })();
        if let Err(message) = result {
            panic!("the web panel could not be built: {message}");
        }
    }
}

/// The desktop window: its identity (product name, application id, title) comes from `branding.toml`, so the window
/// carries the same name as the other executables. `tauri.conf.json` holds the rest.
#[cfg(feature = "gui")]
mod gui {
    use std::{env, path::Path};

    pub fn prepare(branding: &Path) {
        let text = std::fs::read_to_string(branding).unwrap();
        let table: toml::Table = text.parse().unwrap();
        let get = |key: &str| table[key].as_str().unwrap().to_owned();
        let (name, id) = (get("display_name"), get("app_id"));
        // Tauri merges this JSON over tauri.conf.json, both for tauri-build and for the macro that embeds the config.
        let config = format!(
            r#"{{"productName":{name:?},"identifier":{id:?},"app":{{"windows":[{{"title":{name:?},"width":1280,"height":800,"minWidth":720,"minHeight":480}}]}}}}"#
        );
        env::set_var("TAURI_CONFIG", &config);
        println!("cargo:rustc-env=TAURI_CONFIG={config}");
        tauri_build::build();
    }
}
